export const deleteBudget = async (req: any, res: any, next: NextFunction) => {
    const user = req.user
    const { BudgetId } = req.params ?? req.query

    if (!user) {
        return next(new ApiError(404, "User not found."))
    }

    try {
        const budget = await Budget.deleteOne({
            _id: BudgetId,
            user: user._id
        })


        if (budget.deletedCount === 0) {
            return next(new ApiError(404, "Budget not found."))
        }

        res.status(200).json(new ApiResponse(200, null, "Budget deleted successfully!"))

    } catch (error) {
        next(error)
    }

}


